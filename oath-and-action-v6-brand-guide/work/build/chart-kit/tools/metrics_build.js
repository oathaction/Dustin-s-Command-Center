// Measure the advance widths of the chart faces in Chromium and write work/build/chart-kit/metrics.js.
//
// Usage: node work/build/chart-kit/tools/metrics_build.js
//
// Reads the guide's embedded fonts (work/build/assets/fonts/, the Font Manifest's WOFF2 files, OFL 1.1) as @font-face data
// URLs, sets each character alone at 1000 px in a span and records its width in thousandths of an em. Faces: Inter 400,
// 600 and 700 with proportional and tabular figures, Inter Tight 800 (the weights the guide embeds). The kit measures text
// with this table, so a layout is the same in Node and in any browser. Pair kerning is left out; the layout guard keeps a pad.
const fs = require('fs');
const path = require('path');
const { chromium } = require('/opt/node-tools/node_modules/playwright');

const ROOT = path.resolve(__dirname, '../../../..');
const FONTS = path.join(ROOT, 'work/build/assets/fonts');
const OUT = path.join(ROOT, 'work/build/chart-kit/metrics.js');

const files = {
  'Inter': ['inter/20261111_Inter-Latin.woff2', 'inter/20261111_Inter-Latin-Ext.woff2'],
  'Inter Tight': ['inter-tight/20261111_Inter-Tight-Latin.woff2', 'inter-tight/20261111_Inter-Tight-Latin-Ext.woff2'],
};
const chars = [];
for (let c = 32; c < 127; c++) chars.push(String.fromCharCode(c));
for (let c = 160; c < 256; c++) chars.push(String.fromCharCode(c));
for (const c of '‘’“”–−×•…→←↑↓▲▼◆●○■□✓·′″  ⁄≤≥≈±') chars.push(c);
const faces = [
  ['Inter', 400, 'normal'], ['Inter', 600, 'normal'], ['Inter', 700, 'normal'],
  ['Inter', 400, 'tabular'], ['Inter', 600, 'tabular'], ['Inter', 700, 'tabular'],
  ['Inter Tight', 800, 'normal'],
];

(async () => {
  const css = Object.entries(files).map(([fam, fs2]) => fs2.map(f => {
    const b64 = fs.readFileSync(path.join(FONTS, f)).toString('base64');
    return `@font-face{font-family:"${fam}";src:url(data:font/woff2;base64,${b64}) format("woff2");font-weight:100 900;font-style:normal;}`;
  }).join('\n')).join('\n');
  const b = await chromium.launch();
  const p = await b.newPage();
  await p.setContent(`<!doctype html><html><head><style>${css} span{position:absolute;white-space:pre;font-size:1000px;line-height:1;font-kerning:none}</style></head><body></body></html>`);
  const table = await p.evaluate(async ({ chars, faces }) => {
    const out = {};
    for (const [fam, w, num] of faces) {
      await document.fonts.load(`${w} 1000px "${fam}"`, chars.join(''));
      const key = `${fam}|${w}${num === 'tabular' ? '|tnum' : ''}`;
      const s = document.createElement('span');
      s.style.fontFamily = `"${fam}"`;
      s.style.fontWeight = w;
      s.style.fontVariantNumeric = num === 'tabular' ? 'tabular-nums' : 'proportional-nums';
      document.body.appendChild(s);
      const adv = {};
      for (const ch of chars) {
        s.textContent = 'H' + ch + 'H';
        const both = s.getBoundingClientRect().width;
        s.textContent = 'HH';
        adv[ch] = Math.round(both - s.getBoundingClientRect().width);
      }
      s.remove();
      out[key] = adv;
    }
    return out;
  }, { chars, faces });
  // Ascent and descent of each face, measured from a canvas at 1000 px
  const vm = await p.evaluate(async (faces) => {
    const c = document.createElement('canvas').getContext('2d');
    const out = {};
    for (const [fam, w] of faces) {
      c.font = `${w} 1000px "${fam}"`;
      const m = c.measureText('Hxg');
      out[`${fam}|${w}`] = { cap: Math.round(c.measureText('H').actualBoundingBoxAscent), ascent: Math.round(m.fontBoundingBoxAscent), descent: Math.round(m.fontBoundingBoxDescent) };
    }
    return out;
  }, faces);
  await b.close();
  const order = chars.join('');
  const compact = {};
  for (const [k, adv] of Object.entries(table)) compact[k] = chars.map(ch => adv[ch]);
  const js = `// Generated by work/build/chart-kit/tools/metrics_build.js from the guide's embedded fonts. Do not edit by hand.
// Advance widths in thousandths of an em for each character of CHARS, per face; vertical metrics in thousandths.
(function (root) {
  var M = root.OAChartMetrics = root.OAChartMetrics || {};
  M.chars = ${JSON.stringify(order)};
  M.faces = ${JSON.stringify(compact)};
  M.vertical = ${JSON.stringify(vm)};
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
  fs.writeFileSync(OUT, js);
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${Object.keys(compact).length} faces, ${chars.length} characters, ${js.length} bytes`);
})();
