"""Write the chart kit's shared map geometry, work/build/chart-kit/geo.js, from Phase 2's frozen geometry files.

Usage:
    python3 -I work/build/chart-kit/tools/geo_build.py [--tolerance 0.6]

Reads work/boards/phase-2/data-viz/shared/geo/ (us-atlas 3.0.1, ISC license, already projected with d3.geoAlbersUsa
to a 975 by 610 frame; and the studio's square tile grid) and writes one classic script that sets OAChartGeo:
  tiles      {code: [col, row, fips, name]} for the 51-tile grid (12 columns by 8 rows)
  centers    {code: [x, y]} the area centroid of each state's largest polygon, in the 975 by 610 frame
  land       one SVG path of the 50 states and DC, simplified (Douglas-Peucker, tolerance in frame units)
  borders    one SVG path of the interior state borders, simplified the same way
  credit     the credit line the geometry carries
The license text is copied beside it as geo-LICENSE.txt. Maps share this file once per page.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[4]
GEO = ROOT / 'work/boards/phase-2/data-viz/shared/geo'
OUT = ROOT / 'work/build/chart-kit/geo.js'
LIC = ROOT / 'work/build/chart-kit/geo-LICENSE.txt'
TOL = float(sys.argv[sys.argv.index('--tolerance') + 1]) if '--tolerance' in sys.argv else 0.6

topo = json.loads((GEO / 'states-albers-10m.json').read_text())
meta = json.loads((GEO / 'geo.meta.json').read_text())
grid = json.loads((GEO / 'us-state-tile-grid.json').read_text())
sx, sy = topo['transform']['scale']
tx, ty = topo['transform']['translate']

arcs = []
for a in topo['arcs']:
    x = y = 0
    pts = []
    for dx, dy in a:
        x += dx
        y += dy
        pts.append((x * sx + tx, y * sy + ty))
    arcs.append(pts)


def arc(i):
    return arcs[i] if i >= 0 else arcs[~i][::-1]


def ring(idx):
    out = []
    for i in idx:
        p = arc(i)
        out.extend(p if not out else p[1:])
    return out


def dp(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]
        bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        L = (dx * dx + dy * dy) ** 0.5 or 1e-9
        best, bi = 0, None
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / L
            if d > best:
                best, bi = d, i
        if bi is not None and best > tol:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]


def path(rings, closed=True):
    out = []
    for r in rings:
        if len(r) < (4 if closed else 2):
            continue
        s = 'M' + 'L'.join(f'{x:.1f},{y:.1f}' for x, y in r)
        out.append(s + ('Z' if closed else ''))
    return ''.join(out)


def area_centroid(r):
    A = cx = cy = 0
    for (x0, y0), (x1, y1) in zip(r, r[1:] + r[:1]):
        c = x0 * y1 - x1 * y0
        A += c
        cx += (x0 + x1) * c
        cy += (y0 + y1) * c
    A /= 2
    return (abs(A), cx / (6 * A), cy / (6 * A)) if A else (0, r[0][0], r[0][1])


# simplify each arc once, so neighbors share their simplified border
simple = [dp(a, TOL) for a in arcs]


def sarc(i):
    return simple[i] if i >= 0 else simple[~i][::-1]


def sring(idx):
    out = []
    for i in idx:
        p = sarc(i)
        out.extend(p if not out else p[1:])
    return out


fips_code = {g['fips']: g['code'] for g in grid}
centers, land_rings = {}, []
arc_use = {}
for g in topo['objects']['states']['geometries']:
    polys = g['arcs'] if g['type'] == 'MultiPolygon' else [g['arcs']]
    best = (0, 0, 0)
    for poly in polys:
        for k, rr in enumerate(poly):
            for i in rr:
                j = i if i >= 0 else ~i
                arc_use[j] = arc_use.get(j, 0) + 1
            full = ring(rr)
            if k == 0:
                c = area_centroid(full)
                if c[0] > best[0]:
                    best = c
            land_rings.append(sring(rr))
    code = fips_code.get(g['id'])
    if code:
        centers[code] = [round(best[1], 1), round(best[2], 1)]
# interior borders: arcs used by two states
borders = [simple[j] for j, n in arc_use.items() if n > 1]
js = ('// Generated by work/build/chart-kit/tools/geo_build.py from Phase 2\'s frozen geometry. Do not edit by hand.\n'
      '// ' + meta['credit_line'] + ' License: geo-LICENSE.txt (ISC).\n'
      '(function (root) {\n  root.OAChartGeo = ' + json.dumps({
          'frame': [975, 610],
          'tiles': {g['code']: [g['col'], g['row'], g['fips'], g['name']] for g in grid},
          'centers': centers,
          'land': path(land_rings),
          'borders': path(borders, closed=False),
          'credit': meta['credit_line'],
          'tolerance': TOL,
      }, separators=(',', ':')) + ';\n})(typeof globalThis !== \'undefined\' ? globalThis : this);\n')
OUT.write_text(js)
LIC.write_bytes((GEO / 'us-atlas-LICENSE.txt').read_bytes())
print(f'wrote {OUT.relative_to(ROOT)}: {len(js):,} bytes, {len(centers)} centers, {len(grid)} tiles, tolerance {TOL}')
