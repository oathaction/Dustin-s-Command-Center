def node(args, out_json=None):
    r = subprocess.run(["node", *args], capture_output=True, text=True, cwd=ROOT)
    if r.returncode not in (0, 1):
        raise SystemExit(f"check failed to run: {' '.join(args)}\n{r.stderr[-1500:]}")
    return r.returncode, r.stdout


def _full_share(res, scale="1x"):
    s = res["scales"][scale]["soft_edges"]
    return round((s["ink_px"] - s["partial_px"]) / s["ink_px"], 4) if s["ink_px"] else None


