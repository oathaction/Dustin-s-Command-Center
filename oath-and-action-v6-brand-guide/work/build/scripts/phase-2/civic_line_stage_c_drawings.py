# ------------------------------------------------------------------ the first draft of a fit (the record)
def draft_map(icon_id, growth=None):
    """The master's own centerlines, grown toward 22 px (at most 1.35 times) about the box center, rasterized as
    one-pixel lines on the 24 px grid, with filled shapes kept where they cover half a pixel. Every fit began here
    and was then redrawn by hand; this is not the fit."""
    from fontTools.svgLib.path import parse_path
    from fontTools.svgLib.path.shapes import PathBuilder
    from PIL import Image, ImageDraw
    row = inventory()[icon_id]
    K = 24 / 128.0
    g = growth or min(22.0 / (row["extent_units"] * K), 1.35)

    def tx(p):
        return (12 + (p[0] - 64) * K * g, 12 + (p[1] - 64) * K * g)

    class Flat:
        def __init__(self):
            self.polys = []

        def moveTo(self, p):
            self.cur = [p]
            self.polys.append(self.cur)

        def lineTo(self, p):
            self.cur.append(p)

        def curveTo(self, *pts):
            p0 = self.cur[-1]
            for i in range(1, 25):
                t = i / 24
                u = 1 - t
                if len(pts) == 3:
                    (c1, c2, p3) = pts
                    self.cur.append((u ** 3 * p0[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t ** 3 * p3[0],
                                     u ** 3 * p0[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t ** 3 * p3[1]))
            if len(pts) != 3:
                self.cur.extend(pts)

        def qCurveTo(self, *pts):
            p0, c, p2 = self.cur[-1], pts[0], pts[-1]
            for i in range(1, 25):
                t = i / 24
                u = 1 - t
                self.cur.append((u * u * p0[0] + 2 * u * t * c[0] + t * t * p2[0], u * u * p0[1] + 2 * u * t * c[1] + t * t * p2[1]))

        def closePath(self):
            self.cur.append(self.cur[0])

        def endPath(self):
            pass

    def bres(a, b):
        (x0, y0), (x1, y1) = a, b
        out = []
        dx, dy = abs(x1 - x0), -abs(y1 - y0)
        sx, sy = (1 if x0 < x1 else -1), (1 if y0 < y1 else -1)
        err = dx + dy
        while True:
            out.append((x0, y0))
            if (x0, y0) == (x1, y1):
                return out
            e2 = 2 * err
            if e2 >= dy:
                err += dy
                x0 += sx
            if e2 <= dx:
                err += dx
                y0 += sy

    grid = [["."] * 24 for _ in range(24)]
    fills = Image.new("L", (192, 192), 0)
    fd = ImageDraw.Draw(fills)
    root = ET.parse(master_path(row)).getroot()
    ns = "{http://www.w3.org/2000/svg}"
    for grp in root.iter(ns + "g"):
        if grp.get("data-part") not in ("base", "accent"):
            continue
        for el in grp:
            pb = PathBuilder()
            pb.add_path_from_element(el)
            for d in pb.paths:
                pen = Flat()
                parse_path(d, pen)
                for poly in pen.polys:
                    q = [tx(p) for p in poly]
                    if el.get("fill") not in (None, "none"):
                        fd.polygon([(x * 8, y * 8) for x, y in q], fill=255)
                    if el.get("stroke") not in (None, "none"):
                        cells = [(min(23, max(0, int(x))), min(23, max(0, int(y)))) for x, y in q]
                        seq = cells[:1]
                        for i in range(len(cells) - 1):
                            seq += bres(cells[i], cells[i + 1])[1:]
                        for x, y in seq:
                            grid[y][x] = "#"
    f = fills.resize((24, 24), Image.BOX)
    for y in range(24):
        for x in range(24):
            if f.getpixel((x, y)) >= 128:
                grid[y][x] = "#"
    return ["".join(r) for r in grid], g


