R16 = 0.75   # the approved files' corner radius at 16 px


def fmt(v):
    s = f"{v:.3f}".rstrip("0").rstrip(".")
    return "0" if s in ("-0", "") else s


def pause_bar(x0, x1, y0=2.75, y1=13.25, r=R16):
    """One Pause bar's centerline outline between centerlines x0 and x1, as the approved file draws it."""
    return (f"M{fmt(x0 + r)} {fmt(y0)} L{fmt(x1 - r)} {fmt(y0)} A{fmt(r)} {fmt(r)} 0 0 1 {fmt(x1)} {fmt(y0 + r)} "
            f"L{fmt(x1)} {fmt(y1 - r)} A{fmt(r)} {fmt(r)} 0 0 1 {fmt(x1 - r)} {fmt(y1)} L{fmt(x0 + r)} {fmt(y1)} "
            f"A{fmt(r)} {fmt(r)} 0 0 1 {fmt(x0)} {fmt(y1 - r)} L{fmt(x0)} {fmt(y0 + r)} A{fmt(r)} {fmt(r)} 0 0 1 "
            f"{fmt(x0 + r)} {fmt(y0)} Z")


def _isect(p, d, q, e):
    den = d[0] * e[1] - d[1] * e[0]
    t = ((q[0] - p[0]) * e[1] - (q[1] - p[1]) * e[0]) / den
    return (p[0] + t * d[0], p[1] + t * d[1])


def _unit(v):
    n = math.hypot(*v)
    return (v[0] / n, v[1] / n)


def _fillet(p_in, d_in, p_out, d_out, r=R16):
    d_in, d_out = _unit(d_in), _unit(d_out)
    c = _isect(p_in, d_in, p_out, d_out)
    theta = math.acos(max(-1.0, min(1.0, -(d_in[0] * d_out[0] + d_in[1] * d_out[1]))))
    t = r / math.tan(theta / 2)
    a = (c[0] - d_in[0] * t, c[1] - d_in[1] * t)
    b = (c[0] + d_out[0] * t, c[1] + d_out[1] * t)
    return a, b, 1 if (d_in[0] * d_out[1] - d_in[1] * d_out[0]) > 0 else 0


def filter_funnel(xl, xr):
    """The approved Filter outline with its spout's centerlines at xl and xr. The top edge, both cone sides and the
    spout's slanted foot are the approved file's own lines; only the spout's sides move, and every corner keeps the
    r 0.75 fillet. filter_funnel(6.75, 9.25) rebuilds the approved path byte for byte."""
    lines = [((4.31, 2.75), (1, 0)), ((12.275, 3.969), (9.414 - 12.275, 7.545 - 3.969)), ((xr, 0), (0, 1)),
             ((8.835, 12.457), (7.835 - 8.835, 12.957 - 12.457)), ((xl, 0), (0, -1)),
             ((6.586, 7.545), (3.725 - 6.586, 3.969 - 7.545))]
    corners = [_fillet(*lines[i], *lines[(i + 1) % 6]) for i in range(6)]
    d = [f"M{fmt(corners[5][1][0])} {fmt(corners[5][1][1])}"]
    for a, b, s in corners:
        d.append(f"L{fmt(a[0])} {fmt(a[1])} A{fmt(R16)} {fmt(R16)} 0 0 {s} {fmt(b[0])} {fmt(b[1])}")
    return " ".join(d) + " Z"


