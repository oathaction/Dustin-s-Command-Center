def body(svg_text):
    s = re.sub(r"<\?xml[^>]*>\s*", "", svg_text)
    return re.sub(r"<!--.*?-->\s*", "", s, flags=re.S)


def placed(svg_text, x, y, size, extra=""):
    """svg_text as a nested <svg> at (x, y), size by size, keeping its viewBox."""
    s = body(svg_text)
    m = re.search(r"<svg\b[^>]*>", s)
    tag = re.sub(r'\s(width|height|x|y)="[^"]*"', "", m.group(0))
    tag = tag.replace("<svg", f'<svg x="{x}" y="{y}" width="{size}" height="{size}"{extra}', 1)
    return s.replace(m.group(0), tag, 1)


def sheet(w, h, bg, parts, scale=1, color=None):
    """One SVG of w by h CSS px holding parts, drawn at `scale` device px per CSS px."""
    style = f' style="color:{color}"' if color else ""
    return (f'<svg xmlns="http://www.w3.org/2000/svg" width="{w * scale}" height="{h * scale}" viewBox="0 0 {w} {h}"{style}>'
            f'<rect width="{w}" height="{h}" fill="{bg}"/>' + "".join(parts) + "</svg>")


def rows_of(icon_id):
    rows = FITS[icon_id].strip("\n").split("\n")
    assert len(rows) == 24 and all(len(r) == 24 and set(r) <= set(".#") for r in rows), icon_id
    return rows


def runs(rows, c="#"):
    """The pixels of one color as one path of whole-pixel rectangles, one per horizontal run (the pillar fits' way)."""
    d = []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            if row[x] == c:
                x0 = x
                while x < len(row) and row[x] == c:
                    x += 1
                d.append(f"M{x0} {y}h{x - x0}v1h-{x - x0}z")
            else:
                x += 1
    return "".join(d)


